param(
  [switch]$AutoStart,
  [switch]$Remove
)

# Creates (or removes) Desktop / Start Menu shortcuts for the local app window.
# ASCII-only on purpose: no BOM, and PowerShell 5.1 decodes non-ASCII bytes as ANSI.
# The Chinese display names are kept as code points so this file stays ASCII.
$ErrorActionPreference = "Stop"

$root = Split-Path -Parent $PSScriptRoot
$shell = New-Object -ComObject WScript.Shell
$wscript = Join-Path $env:SystemRoot "System32\wscript.exe"
$vbs = Join-Path $root "app-shell.vbs"
# Shortcuts point at app-icon.ico, not favicon.ico: Windows caches shortcut icons by
# path, so changed artwork under the same name can keep showing the old picture until
# the cache is rebuilt. A distinct file name forces a fresh read.
$iconPath = Join-Path $root "apps\studio-web\public\app-icon.ico"

function New-Text([int[]]$codes) {
  return -join ($codes | ForEach-Object { [char]$_ })
}

# app name:      content creation platform
$appName = New-Text @(0x5185, 0x5BB9, 0x521B, 0x4F5C, 0x5E73, 0x53F0)
# stop shortcut: stop + app name
$stopName = New-Text @(0x505C, 0x6B62, 0x5185, 0x5BB9, 0x521B, 0x4F5C, 0x5E73, 0x53F0)

$desktop = [Environment]::GetFolderPath("Desktop")
$programs = [Environment]::GetFolderPath("Programs")
$startup = [Environment]::GetFolderPath("Startup")

# The tray build ships a single shortcut: closing the app window shuts everything
# down, so no separate stop icon is needed. Older installs did put one on the
# Desktop; it is removed below so the desktop shows exactly one icon.
$legacyStop = Join-Path $desktop ($stopName + ".lnk")

$targets = @(
  (Join-Path $desktop ($appName + ".lnk")),
  (Join-Path $programs ($appName + ".lnk")),
  (Join-Path $startup ($appName + ".lnk"))
)

function New-AppIcon([string]$IconFile) {
  # Fallback only. The real artwork ships as apps/studio-web/public/app-icon.ico,
  # generated by scripts/make-app-icon.py (Pillow, multi-size ICO). This drawing
  # path exists so a fresh clone without that file can still install shortcuts.
  if (Test-Path -LiteralPath $IconFile) { return $true }
  try {
    Add-Type -AssemblyName System.Drawing
    $size = 256
    $bitmap = New-Object System.Drawing.Bitmap $size, $size
    $graphics = [System.Drawing.Graphics]::FromImage($bitmap)
    $graphics.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::AntiAlias

    # rounded-square gradient background
    $rect = New-Object System.Drawing.Rectangle 0, 0, $size, $size
    $from = [System.Drawing.Color]::FromArgb(99, 102, 241)
    $to = [System.Drawing.Color]::FromArgb(168, 85, 247)
    $brush = New-Object System.Drawing.Drawing2D.LinearGradientBrush -ArgumentList $rect, $from, $to, 45.0
    $shape = New-Object System.Drawing.Drawing2D.GraphicsPath
    $r = [int]($size * 0.225)
    $d = $r * 2
    $shape.AddArc(0, 0, $d, $d, 180, 90)
    $shape.AddArc($size - $d, 0, $d, $d, 270, 90)
    $shape.AddArc($size - $d, $size - $d, $d, $d, 0, 90)
    $shape.AddArc(0, $size - $d, $d, $d, 90, 90)
    $shape.CloseFigure()
    $graphics.FillPath($brush, $shape)

    # white four-point sparkle
    $cx = $size * 0.5
    $cy = $size * 0.505
    $outer = $size * 0.33
    $inner = $outer * 0.24
    $pts = New-Object 'System.Collections.Generic.List[System.Drawing.PointF]'
    foreach ($i in 0..3) {
      $ao = (-90 + $i * 90) * [Math]::PI / 180
      $ai = (-45 + $i * 90) * [Math]::PI / 180
      $pts.Add([System.Drawing.PointF]::new([float]($cx + $outer * [Math]::Cos($ao)), [float]($cy + $outer * [Math]::Sin($ao))))
      $pts.Add([System.Drawing.PointF]::new([float]($cx + $inner * [Math]::Cos($ai)), [float]($cy + $inner * [Math]::Sin($ai))))
    }
    $white = New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::White)
    $graphics.FillPolygon($white, $pts.ToArray())
    $graphics.Dispose()

    $icon = [System.Drawing.Icon]::FromHandle($bitmap.GetHicon())
    $stream = [System.IO.File]::Create($IconFile)
    $icon.Save($stream)
    $stream.Close()
    $icon.Dispose()
    $bitmap.Dispose()
    Write-Host ("icon created (fallback): " + $IconFile)
    return $true
  } catch {
    Write-Host ("icon generation skipped: " + $_.Exception.Message)
    return $false
  }
}

function New-AppShortcut([string]$path, [string]$extraArgs, [string]$icon) {
  $shortcut = $shell.CreateShortcut($path)
  $shortcut.TargetPath = $wscript
  if ([string]::IsNullOrWhiteSpace($extraArgs)) {
    $shortcut.Arguments = '"{0}"' -f $vbs
  } else {
    $shortcut.Arguments = '"{0}" {1}' -f $vbs, $extraArgs
  }
  $shortcut.WorkingDirectory = $root
  if ($icon) { $shortcut.IconLocation = ($icon + ",0") }
  $shortcut.Description = $appName
  $shortcut.Save()
  Write-Host ("shortcut created: " + $path)
}

if ($Remove) {
  foreach ($target in $targets) {
    if (Test-Path -LiteralPath $target) {
      try { [System.IO.File]::Delete($target) } catch { }
      Write-Host ("shortcut removed: " + $target)
    }
  }
  if (Test-Path -LiteralPath $legacyStop) {
    try { [System.IO.File]::Delete($legacyStop) } catch { }
    Write-Host ("shortcut removed: " + $legacyStop)
  }
  Write-Host "done"
  exit 0
}

$hasIcon = New-AppIcon $iconPath
$icon = ""
if ($hasIcon) { $icon = $iconPath }

New-AppShortcut (Join-Path $desktop ($appName + ".lnk")) "" $icon
New-AppShortcut (Join-Path $programs ($appName + ".lnk")) "" $icon

if (Test-Path -LiteralPath $legacyStop) {
  # .NET delete keeps working even when a tool wraps Remove-Item (some sandboxes do).
  try { [System.IO.File]::Delete($legacyStop) } catch { }
  Write-Host ("legacy stop shortcut removed: " + $legacyStop)
}

if ($AutoStart) {
  New-AppShortcut (Join-Path $startup ($appName + ".lnk")) "" $icon
  Write-Host "autostart enabled"
} elseif (Test-Path (Join-Path $startup ($appName + ".lnk"))) {
  Write-Host "autostart shortcut already present (kept)"
}

Write-Host "done"
